import 'dart:io';

import 'package:flutter/foundation.dart';
import 'package:flutter/services.dart';
import 'package:flutter_foreground_task/flutter_foreground_task.dart';

import '../../i18n/strings.g.dart';
import '../../utils/platform_info.dart';
import 'local_notifications_service.dart';

/// Runs an Android foreground service for as long as sessions are connected.
///
/// The service does no work of its own. Its only job is to hold the process at
/// foreground importance so the cached-process freezer and the low-memory
/// killer leave the SSH transports alone, and to hold the wake and WiFi locks
/// that keep [SshService]'s keepalive timer firing while the screen is off.
///
/// This does not replace the remote helper: a changed IP or a long enough
/// outage still drops the transport, and only the server-side session survives
/// that. It buys the common case - app backgrounded for a while - a live socket
/// instead of a reconnect.
class ForegroundNotificationService {
  ForegroundNotificationService._();

  static final instance = ForegroundNotificationService._();

  static const _systemChannel = MethodChannel('dev.termphin.termphin/system');

  static const _serviceId = 271;
  static const _channelId = 'termphin_sessions';

  /// A notification small icon is an alpha mask: the system discards the
  /// colours, tints what is left and draws it in a circle. Left unset the
  /// plugin falls back to `@mipmap/ic_launcher`, whose alpha is a solid
  /// square, so the mark arrives as a featureless blob. `ic_stat_termphin` is
  /// the same dolphin flattened to a silhouette with the eye punched through
  /// it, generated by `scripts/generate_icons.py`. The background colour
  /// fills the circle the tinted silhouette sits in.
  static const _notificationIcon = NotificationIcon(
    metaDataName: 'dev.termphin.notification_icon',
    backgroundColor: Color(0xFF3795FB),
  );

  bool _configured = false;
  int _sessionCount = 0;
  String? _shownText;
  Future<void> _queue = Future<void>.value();

  bool get supported => !kIsWeb && Platform.isAndroid;

  /// Nothing to load any more - the service is not optional, since a frozen
  /// process drops every SSH socket it holds. What the user can still decide
  /// is whether Android is allowed to run it unrestricted, which lives in the
  /// system's own battery settings.
  Future<void> init() async {}

  /// Starts, updates or stops the service to match [count] live sessions.
  Future<void> syncSessions(int count) {
    if (count == _sessionCount) return _queue;
    _sessionCount = count;
    return _apply();
  }

  Future<bool> get isIgnoringBatteryOptimizations async =>
      supported && await FlutterForegroundTask.isIgnoringBatteryOptimizations;

  /// Asks for the exemption when there is one to ask for, and otherwise opens
  /// the system screen that shows it - the request dialog is a no-op once the
  /// app is already exempt, which would look like a dead tap.
  Future<void> requestIgnoreBatteryOptimization() async {
    if (!supported) return;
    if (await FlutterForegroundTask.isIgnoringBatteryOptimizations) {
      await FlutterForegroundTask.openIgnoreBatteryOptimizationSettings();
      return;
    }
    await FlutterForegroundTask.requestIgnoreBatteryOptimization();
  }

  /// The permission is one question wherever it is asked, so the three methods
  /// below answer for both platforms and the screens that draw the row need
  /// not know which side owns it. On Android it belongs to the foreground
  /// service; on iOS there is no such service and the permission is the
  /// notification centre's, held by [LocalNotificationsService] along with the
  /// transfer notifications that are the only thing posted there.
  ///
  /// True below Android 13, where posting a notification needs no permission.
  Future<bool> get hasNotificationPermission async {
    if (isIOSPlatform) {
      return LocalNotificationsService.instance.hasPermission();
    }
    return !supported ||
        await FlutterForegroundTask.checkNotificationPermission() ==
            NotificationPermission.granted;
  }

  /// Returns the permission state after the system prompt closes. A permission
  /// already answered cannot be asked for again - the dialog is only shown
  /// once - so that case goes to the system screen instead, which is the only
  /// place the switch still exists.
  Future<bool> requestNotificationPermission() async {
    if (isIOSPlatform) {
      return LocalNotificationsService.instance.requestPermission();
    }
    if (!supported) return true;
    final result = await FlutterForegroundTask.requestNotificationPermission();
    if (result == NotificationPermission.permanently_denied) {
      await openNotificationSettings();
    }
    return result == NotificationPermission.granted;
  }

  /// Opens the system notification settings. Nothing to open on this device
  /// just leaves the row doing nothing.
  Future<void> openNotificationSettings() async {
    if (isIOSPlatform) return LocalNotificationsService.instance.openSettings();
    if (!supported) return;
    try {
      await _systemChannel.invokeMethod('openNotificationSettings');
    } on PlatformException catch (_) {}
  }

  /// Serialised so a burst of session changes cannot interleave a start with a
  /// stop and leave the service in the wrong state.
  Future<void> _apply() {
    if (!supported) return _queue;
    final next = _queue.then((_) => _reconcile()).catchError((Object error) {
      debugPrint('Foreground service sync failed: $error');
    });
    _queue = next;
    return next;
  }

  Future<void> _reconcile() async {
    if (_sessionCount == 0) {
      if (await FlutterForegroundTask.isRunningService) {
        await FlutterForegroundTask.stopService();
      }
      _shownText = null;
      return;
    }

    _configure();
    final (:title, :text) = sessionNotificationContent(_sessionCount);
    if (await FlutterForegroundTask.isRunningService) {
      if (title == _shownText) return;
      await FlutterForegroundTask.updateService(
        notificationTitle: title,
        notificationText: text,
        notificationIcon: _notificationIcon,
      );
    } else {
      await _ensureNotificationPermission();
      final result = await FlutterForegroundTask.startService(
        serviceId: _serviceId,
        serviceTypes: const [ForegroundServiceTypes.dataSync],
        notificationTitle: title,
        notificationText: text,
        notificationIcon: _notificationIcon,
      );
      if (result is ServiceRequestFailure) {
        _shownText = null;
        throw result.error;
      }
    }
    _shownText = title;
  }

  void _configure() {
    if (_configured) return;
    _configured = true;
    FlutterForegroundTask.init(
      androidNotificationOptions: AndroidNotificationOptions(
        channelId: _channelId,
        channelName: t.background.channelName,
        channelDescription: t.background.channelDescription,
        channelImportance: NotificationChannelImportance.LOW,
        priority: NotificationPriority.LOW,
        onlyAlertOnce: true,
      ),
      iosNotificationOptions: const IOSNotificationOptions(
        showNotification: false,
        playSound: false,
      ),
      foregroundTaskOptions: ForegroundTaskOptions(
        eventAction: ForegroundTaskEventAction.nothing(),
        allowWakeLock: true,
        allowWifiLock: true,
      ),
    );
  }

  /// Without the permission the service still runs, it just posts no
  /// notification - so a refusal is not treated as a failure.
  Future<void> _ensureNotificationPermission() async {
    final permission =
        await FlutterForegroundTask.checkNotificationPermission();
    if (permission != NotificationPermission.granted) {
      await FlutterForegroundTask.requestNotificationPermission();
    }
  }
}

/// What the session notification says. The system already heads it with the
/// app's name, so the title is the news - how many sessions are held - rather
/// than the name a second time.
({String title, String text}) sessionNotificationContent(int count) => (
  title: count == 1
      ? t.background.notificationTitleOne
      : t.background.notificationTitleOther(count: count),
  text: t.background.notificationText,
);
