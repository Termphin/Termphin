import 'dart:convert';

import '../../models/remote_shell.dart';

/// OSC code carrying Termphin's run-completion marker.
///
/// Deliberately outside the range any terminal assigns meaning to: the
/// vendored Termux emulator routes unknown OSC codes to `unknownParameter()`
/// and drops them, so the marker never reaches the screen and needs no
/// stripping. Anything reading the byte stream can still watch for it.
const snippetMarkerOsc = 5379;

/// The bytes a finished run emits, as they appear in the output stream:
/// `ESC ] 5379 ; termphin ; <runId> ; <exitCode> BEL`.
///
/// [runId] is generated by the app and must stay free of `;` so the marker
/// keeps four fields.
String snippetMarker(String runId, int exitCode) =>
    ']$snippetMarkerOsc;termphin;$runId;$exitCode';

/// How to get one snippet running in a session.
///
/// Split in two because the two halves travel by different routes, which is
/// the whole point: [setupCommand] goes over a separate SSH exec channel
/// where command length, echo and line editing are non-issues, leaving
/// [terminalInput] short enough to type into the interactive shell without
/// tripping readline, bracketed paste or the PTY's line limit.
class SnippetExecution {
  const SnippetExecution({required this.terminalInput, this.setupCommand});

  /// Run over an exec channel before [terminalInput] is sent. Null when the
  /// command is simple enough to type directly.
  final String? setupCommand;

  /// Written to the session's stdin, carriage return included.
  final String terminalInput;
}

/// Plans how to execute [command] in a session.
///
/// A single-line command with nothing to report back is sent as-is: it lands
/// in the shell exactly as if the user had typed it, history and all. Anything
/// else - a multi-line body, or a run that has to report its exit code - is
/// staged as a script file instead. Feeding a long body through the terminal
/// keystroke by keystroke is what breaks on `if` blocks, heredocs, quoting and
/// readline's line length; a file sidesteps all of it and keeps the visible
/// command down to one short line.
///
/// Passing [runId] makes the script report its own exit status by emitting
/// [snippetMarker] on the way out, which is the only way a caller watching the
/// output stream can tell "still running" from "done, and here is the code".
/// The marker is emitted from an EXIT trap, so a body that calls `exit`
/// directly still reports.
SnippetExecution prepareSnippetExecution({
  required String command,
  required RemoteShellType shellType,
  String? runId,
  String? scriptId,
}) {
  final normalized = command.replaceAll('\r\n', '\n').replaceAll('\r', '\n');
  final body = normalized.trimRight();
  if (!body.contains('\n') && runId == null) {
    return SnippetExecution(terminalInput: '$body\r');
  }
  return shellType == RemoteShellType.powershell
      ? _inlinePowerShell(body, runId)
      : _stageUnix(body, runId, scriptId ?? _scriptId());
}

String _scriptId() => DateTime.now().microsecondsSinceEpoch.toRadixString(36);

/// Wrapped in single quotes for the remote shell. Script ids are generated,
/// so this only has to survive the characters this file itself produces.
String _quote(String value) => "'${value.replaceAll("'", r"'\''")}'";

/// Stages [body] as a script file at a path keyed by [id] and runs it.
///
/// The EXIT trap runs on any exit, including `exit 1` inside the body, so
/// the status is always reported and the file always cleans itself up. The
/// script is piped through `base64 -d` rather than `echo`d directly, since
/// `printf`, not dash's `echo`, is what survives the encoded bytes intact.
SnippetExecution _stageUnix(String body, String? runId, String id) {
  final path = '/tmp/.termphin-snippet-$id.sh';
  final report = runId == null
      ? ''
      : ' printf "\\033]$snippetMarkerOsc;termphin;$runId;%d\\007" "\$st";';
  final cleanup = 'trap \'st=\$?; rm -f "\$0";$report\' EXIT';
  final script = '$cleanup\n$body\n';
  final encoded = base64Encode(utf8.encode(script));
  return SnippetExecution(
    setupCommand: "printf %s '$encoded' | base64 -d > ${_quote(path)}",
    terminalInput: 'sh ${_quote(path)}\r',
  );
}

/// PowerShell hosts get the body typed straight in, marker and all.
///
/// Staging is not available to them: the exec channel runs the staging
/// command through `/bin/sh`, which a Windows host does not have. Typing the
/// body has the drawbacks staging exists to avoid - the reporting statement is
/// visible, and a long body still goes through the console line by line - but
/// a staging command that cannot run anywhere is worse than a plain one that
/// does.
///
/// Every line is joined with CR, since that is what the console reads as
/// Enter. `$LASTEXITCODE` stays null until an external command sets it, so
/// a pure-cmdlet body would otherwise report an empty status - it is
/// coerced to 0 before being reported.
SnippetExecution _inlinePowerShell(String body, String? runId) {
  final typed = body.split('\n').join('\r');
  if (runId == null) return SnippetExecution(terminalInput: '$typed\r');
  final report =
      '\$c = \$LASTEXITCODE; if (\$null -eq \$c) { \$c = 0 }; '
      'Write-Host -NoNewline '
      '"\$([char]27)]$snippetMarkerOsc;termphin;$runId;\$c\$([char]7)"';
  return SnippetExecution(terminalInput: '$typed\r$report\r');
}
